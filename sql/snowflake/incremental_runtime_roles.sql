-- Apply with an authorized existing grant owner. Assign these roles to the existing
-- runtime user separately. No runtime process uses ACCOUNTADMIN by default.
CREATE ROLE IF NOT EXISTS FOODY_PIPELINE;
CREATE ROLE IF NOT EXISTS FOODY_DBT;
CREATE ROLE IF NOT EXISTS FOODY_AI_READER;
GRANT USAGE ON WAREHOUSE FOODY_WH TO ROLE FOODY_PIPELINE;
GRANT USAGE ON WAREHOUSE FOODY_WH TO ROLE FOODY_DBT;
GRANT USAGE ON WAREHOUSE FOODY_WH TO ROLE FOODY_AI_READER;
GRANT USAGE ON DATABASE FOODY TO ROLE FOODY_PIPELINE;
GRANT USAGE ON DATABASE FOODY TO ROLE FOODY_DBT;
GRANT USAGE ON DATABASE FOODY TO ROLE FOODY_AI_READER;
GRANT USAGE ON SCHEMA FOODY.RAW TO ROLE FOODY_PIPELINE;
GRANT USAGE ON SCHEMA FOODY.STAGING TO ROLE FOODY_PIPELINE;
GRANT SELECT ON ALL TABLES IN SCHEMA FOODY.STAGING TO ROLE FOODY_PIPELINE;
GRANT SELECT ON ALL VIEWS IN SCHEMA FOODY.STAGING TO ROLE FOODY_PIPELINE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FOODY.STAGING TO ROLE FOODY_PIPELINE;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FOODY.STAGING TO ROLE FOODY_PIPELINE;
GRANT SELECT, INSERT, UPDATE ON TABLE FOODY.RAW.ORDERS TO ROLE FOODY_PIPELINE;
GRANT SELECT, INSERT, UPDATE ON TABLE FOODY.RAW.REVIEWS TO ROLE FOODY_PIPELINE;
GRANT SELECT, INSERT ON TABLE FOODY.RAW.EVENT_INGEST_AUDIT TO ROLE FOODY_PIPELINE;
GRANT SELECT, UPDATE ON TABLE FOODY.RAW.EVENT_PIPELINE_LOCK TO ROLE FOODY_PIPELINE;
GRANT USAGE ON SCHEMA FOODY.RAW TO ROLE FOODY_DBT;
GRANT SELECT ON TABLE FOODY.RAW.ORDERS TO ROLE FOODY_DBT;
GRANT SELECT ON TABLE FOODY.RAW.REVIEWS TO ROLE FOODY_DBT;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA FOODY.STAGING TO ROLE FOODY_DBT;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA FOODY.MART TO ROLE FOODY_DBT;
-- Transfer only the active project's six existing relations to FOODY_DBT using
-- COPY CURRENT GRANTS after inspecting SHOW TABLES/SHOW VIEWS and their owners.
-- This preserves downstream read grants; do not transfer unrelated legacy relations.
GRANT USAGE ON SCHEMA FOODY.STAGING TO ROLE FOODY_AI_READER;
GRANT USAGE ON SCHEMA FOODY.MART TO ROLE FOODY_AI_READER;
GRANT SELECT ON VIEW FOODY.STAGING.STG_ORDERS TO ROLE FOODY_AI_READER;
GRANT SELECT ON VIEW FOODY.STAGING.STG_REVIEWS TO ROLE FOODY_AI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FOODY.STAGING TO ROLE FOODY_AI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA FOODY.MART TO ROLE FOODY_AI_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA FOODY.MART TO ROLE FOODY_AI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA FOODY.MART TO ROLE FOODY_AI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA FOODY.MART TO ROLE FOODY_AI_READER;
