-- Additive migration; run once with the existing schema owner before enabling ingestion.
-- No canonical rows are deleted, reloaded, renumbered, or truncated.
ALTER TABLE __DATABASE__.RAW.ORDERS ADD COLUMN IF NOT EXISTS LAST_EVENT_SEQUENCE NUMBER;
ALTER TABLE __DATABASE__.RAW.ORDERS ADD COLUMN IF NOT EXISTS LAST_EVENT_ID VARCHAR;
ALTER TABLE __DATABASE__.RAW.REVIEWS ADD COLUMN IF NOT EXISTS LAST_EVENT_SEQUENCE NUMBER;
ALTER TABLE __DATABASE__.RAW.REVIEWS ADD COLUMN IF NOT EXISTS LAST_EVENT_ID VARCHAR;
CREATE TABLE IF NOT EXISTS __DATABASE__.RAW.EVENT_INGEST_AUDIT (
    EVENT_ID VARCHAR, S3_KEY VARCHAR, S3_ETAG VARCHAR, EVENT_SEQUENCE NUMBER,
    EVENT_TYPE VARCHAR, APPLIED_AT TIMESTAMP_NTZ
);
CREATE TABLE IF NOT EXISTS __DATABASE__.RAW.EVENT_PIPELINE_LOCK (LOCK_ID NUMBER, LOCK_TOKEN VARCHAR);
INSERT INTO __DATABASE__.RAW.EVENT_PIPELINE_LOCK (LOCK_ID,LOCK_TOKEN)
SELECT 1,'provisioned' WHERE NOT EXISTS (SELECT 1 FROM __DATABASE__.RAW.EVENT_PIPELINE_LOCK WHERE LOCK_ID=1);

